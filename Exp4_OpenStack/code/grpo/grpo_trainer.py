def select_persona_ids(n_personas: int, count: int, *, seed: int, iteration: int) -> List[int]:
    """Which personas this iteration runs, and in what order.

    Args:
        n_personas: size of the full permutation set (96 for the V3 patients).
        count: how many to run this iteration (``NUM_CONVERSATIONS_PER_ITER``).
        seed: the run seed.
        iteration: 1-based loop counter. The final generate-only pass uses
            ``num_iterations + 1``, matching Exp3's convention.

    Returns:
        ``count`` STABLE persona ids (0-based indices into ``generate_all_permutations()``
        order), shuffled by ``Random(seed + iteration)``.

    Notes:
        The shuffle decides WHICH personas run and in what order they are processed. It never
        reaches a filename: ``core.conversations`` names every conversation ``pers<PID>.csv`` by
        the stable persona id, so ``pers07.csv`` is persona 7 in every iteration of every arm
        (Exp3 fix #2). If you came from Exp3, this is the thing that changed -- there is nothing
        to replay, and pairing across iterations is a join on ``persona_id``.

        When ``count >= n_personas`` every persona runs and the shuffle only reorders the
        processing, which still matters: it decides which personas share a generation batch.
    """
    if n_personas <= 0:
        raise ValueError("select_persona_ids: the permutation set is empty")
    ids = list(range(int(n_personas)))
    random.Random(int(seed) + int(iteration)).shuffle(ids)
    return ids[: max(0, int(count))]


def ensure_servers_alive(
    handles: Optional[Mapping[str, Any]],
    *,
    client_factory: Optional[Callable[[], Any]] = None,
    phase: str = "",
) -> Optional[Any]:
    """Probe every vLLM server at a phase boundary; relaunch any that stopped answering.

    Args:
        handles: the ``{model: ServerHandle}`` dict ``tools.vllm_serve.serve_roles`` returned.
            ``None`` or empty is a no-op -- an arm whose roles are all vendor APIs has no
            process to watch.
        client_factory: builds a fresh async client. Called only when a server was actually
            restarted.
        phase: label for the log line (``"generate"``, ``"train"``, ...).

    Returns:
        A fresh client when a restart happened AND *client_factory* was supplied; ``None``
        otherwise. ``None`` means "keep using the client you have".

    Raises:
        RuntimeError: from :func:`tools.vllm_serve.ensure_alive` when a handle exhausts its
            restart budget. A server that keeps dying is a configuration problem -- almost
            always ``gpu_memory_utilization`` colliding with the trainer's peak -- and it should
            stop the run rather than present itself as a mysterious slowdown.

    Notes:
        **A restart invalidates every cached client.** ``roles.make_client`` caches by binding,
        and the cached client holds a connection pool to a process that no longer exists; the
        symptom is a burst of connection errors on the next phase, blamed on the wrong thing.
        This calls ``roles.reset_client_cache()`` after any restart. If no *client_factory* was
        given the caller is still holding the stale object, so that case warns loudly instead of
        pretending it recovered.
    """
    if not handles:
        return None
    restarted = 0
    for handle in list(handles.values()):
        before = int(getattr(handle, "restarts", 0))
        ensure_alive(handle)
        if int(getattr(handle, "restarts", 0)) > before:
            restarted += 1
    if not restarted:
        return None

    dropped = reset_client_cache()
    label = f" before {phase}" if phase else ""
    print(f"{_LOG}vLLM: {restarted} server(s) restarted{label}; dropped {dropped} cached client(s)")
    if client_factory is None:
        _warn(
            "a vLLM server was restarted but no client_factory was given -- the client still in "
            "use holds a connection pool to the dead process. Rebuild it with "
            "roles.make_client(binding) before the next phase."
        )
        return None
    return client_factory()


def ensure_peft_policy(policy, cfg: GRPOTrainingConfig, tokenizer):
    """Return *policy* with a trainable LoRA adapter attached, wrapping it if it has none.

    Args:
        policy: the therapist policy -- a bare base model on a fresh iteration 1, or the
            ``PeftModel`` ``core.policy.resolve_start_state`` handed back on a resume.
        cfg: supplies ``lora_r`` / ``lora_alpha`` / ``lora_dropout`` / ``lora_target_modules``.
        tokenizer: re-bound into ``generate`` by :func:`core.policy.patch_generate`.

    Returns:
        A PEFT-wrapped policy (the same object when it already was one).

    Notes:
        **Why the adapter is attached here and not by ``GRPOTrainer(peft_config=...)``.** The
        reward closure captures this object so that K-turn look-ahead rolls out under the weights
        being trained. Let the trainer do the wrapping and the closure holds the *unwrapped base*
        instead: every simulated therapist turn of that iteration comes from a policy with no
        adapter. Nothing raises, and at step 0 nothing even differs -- a freshly-initialised LoRA
        is numerically identity -- so the divergence grows silently through the iteration. TRL is
        therefore always handed ``peft_config=None`` (see :func:`run_training_phase`); the two
        choices are mutually exclusive and this is the one Exp4 makes.

        **Call it AFTER the generation phase.** Iteration 1 must generate ``model_iter_0`` with
        the genuinely untrained base policy; attaching first would be numerically identical but
        would make the "base" folder a claim rather than a fact.
    """
    if hasattr(policy, "peft_config"):
        patch_generate(policy, tokenizer)
        return policy
    wrapped = attach_lora(
        policy,
        r=cfg.lora_r,
        alpha=cfg.lora_alpha,
        dropout=cfg.lora_dropout,
        target_modules=cfg.lora_target_modules,
    )
    patch_generate(wrapped, tokenizer)
    return wrapped


