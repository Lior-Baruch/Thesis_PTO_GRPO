def extract_training_prompts(
    states: Sequence[Any],
    *,
    tokenizer,
    gen: GenConfig,
    therapist_system_prompt: str,
    permutations: Sequence[Dict[str, str]],
) -> List[Dict[str, Any]]:
    """Slice finished conversations into per-turn training samples under the MCL filter.

    Args:
        states: the conversations from :func:`run_generation_phase`.
        gen: supplies ``min_conv_length`` (MCL) and ``max_prompt_tokens``.
        permutations: the FULL permutation list, indexed by persona id -- it is where each
            sample's ``patient_system_prompt`` comes from.

    Returns:
        One dict per eligible slice, carrying :data:`DATASET_COLUMNS`.

    Notes:
        MCL is the response to the reward-faithfulness finding: a partial cut is what the
        training reward grades, while the experiment evaluates whole conversations, and pairwise
        rank agreement between the two is barely above chance at 2 utterances and only clears 0.8
        near 10. A slice shorter than MCL is dropped rather than down-weighted.
    """
    samples = extract_prompts_from_conversations(
        states,
        therapist_system_prompt,
        tokenizer,
        min_conv_length=gen.min_conv_length,
        max_prompt_tokens=gen.max_prompt_tokens,
        permutations=permutations,
    )
    print(
        f"{_LOG}Extracted {len(samples)} training prompts from {len(states)} conversations "
        f"(MCL={gen.min_conv_length}, max_prompt_tokens={gen.max_prompt_tokens})"
    )
    return samples


def _to_dataset(samples: Sequence[Mapping[str, Any]]) -> Dataset:
    """Build an HF ``Dataset`` carrying exactly :data:`DATASET_COLUMNS`."""
    missing = [c for c in DATASET_COLUMNS if samples and c not in samples[0]]
    if missing:
        raise ValueError(
            f"training samples are missing {missing}; every one of {list(DATASET_COLUMNS)} is "
            f"needed downstream (transcript -> the oracle, patient_system_prompt -> look-ahead, "
            f"persona_id/conversation_id -> the EDA join). "
            f"core.conversations.extract_prompts_from_conversations produces all five."
        )
    return Dataset.from_dict({c: [s[c] for s in samples] for c in DATASET_COLUMNS})


def build_dataset(
    samples: Sequence[Mapping[str, Any]],
    *,
    eval_split_ratio: float,
    seed: int,
    verbose: bool = True,
) -> Tuple[Dataset, Optional[Dataset]]:
    """Split per-turn samples into train/eval HuggingFace datasets, grouped by CONVERSATION.

    Args:
        samples: what :func:`extract_training_prompts` returned.
        eval_split_ratio: fraction of CONVERSATIONS (not samples) held out.
        seed: shuffles the conversation ids. Fixed across iterations on purpose -- the personas
            themselves are already reshuffled per iteration, and re-seeding here as well would
            make the eval split move for two independent reasons.
        verbose: print the split summary.

    Returns:
        ``(train_dataset, eval_dataset)``. ``eval_dataset`` is ``None`` when the split is empty
        (``eval_split_ratio`` of 0, or a single conversation), which
        :func:`build_grpo_config` reads as "run no evaluation".

    Raises:
        ValueError: no samples at all, or a sample missing a required column. An empty prompt set
            means the conversations are shorter than MCL or the generation phase produced
            nothing; training on zero rows would otherwise succeed and write an adapter that
            learned nothing.

    Notes:
        **The split is at CONVERSATION level, never sample level.** Every slice of one
        conversation shares its opening turns, so a sample-level split puts near-identical
        contexts on both sides and the eval reward becomes a measurement of memorisation. The
        overlap is asserted, not assumed.

        Eval is not free here: with ``eval_strategy="epoch"`` TRL samples ``G`` completions for
        every eval prompt and the reward function grades all of them, so the held-out fraction is
        also a fraction of the oracle bill (which, on the open stack, is GPU time rather than
        money -- but it is still time).
    """
    if not samples:
        raise ValueError(
            "build_dataset: no training prompts. Either the generation phase produced no usable "
            "conversations, or every conversation is shorter than MIN_CONV_LENGTH."
        )

    groups: Dict[Any, List[Mapping[str, Any]]] = defaultdict(list)
    for sample in samples:
        groups[sample["conversation_id"]].append(sample)

    conv_ids = sorted(groups)
    random.Random(int(seed)).shuffle(conv_ids)

    ratio = float(eval_split_ratio)
    n_eval = int(len(conv_ids) * ratio)
    if ratio > 0.0:
        n_eval = max(1, n_eval)
    # Train must never be empty; with one conversation there is nothing to hold out.
    n_eval = max(0, min(n_eval, len(conv_ids) - 1))

    eval_ids = set(conv_ids[:n_eval])
    train_ids = set(conv_ids[n_eval:])
    overlap = train_ids & eval_ids
    if overlap:
        raise ValueError(f"build_dataset: train/eval conversation overlap {sorted(overlap)}")

    train_samples = [s for cid in sorted(train_ids) for s in groups[cid]]
    eval_samples = [s for cid in sorted(eval_ids) for s in groups[cid]]

    n_missing_patient = sum(1 for s in samples if not s.get("patient_system_prompt"))
    if n_missing_patient:
        _warn(
            f"{n_missing_patient}/{len(samples)} samples carry an EMPTY patient_system_prompt. "
            f"At K>0 look-ahead would roll out against a default patient instead of the one the "
            f"conversation was generated with, silently changing what the reward measures."
        )

    train_dataset = _to_dataset(train_samples)
    eval_dataset = _to_dataset(eval_samples) if eval_samples else None

    if verbose:
        print(
            f"{_LOG}Split: {len(train_ids)} train / {len(eval_ids)} eval conversations "
            f"(grouped, 0 overlap) -> {len(train_dataset)} / "
            f"{len(eval_dataset) if eval_dataset is not None else 0} prompts"
        )
    return train_dataset, eval_dataset


