"""grpo_trainer.py -- the pieces one GRPO iteration is composed from.

The orchestration LOOP lives in ``train_grpo.ipynb``, visibly, where a human can read what the
run is about to do. This module holds the functions that loop calls, and nothing else: there is
deliberately no ``run_iterative_training`` here. Exp3 had one, it duplicated the notebook loop,
and the two drifted -- the notebook grew a look-ahead state and a TB logger the convenience
wrapper never learned about, so calling it silently ran a different experiment.

One iteration, in the order the functions appear below:

1. **Generate.** The current policy simulates ``num_conversations_per_iter`` conversations
   against the patient simulator, one per persona, into
   ``conversations/<ARM>/model_iter_{n-1}/``. Those conversations ARE the eval set for model
   state ``n-1``; there is no separate eval pass, which is why the folder is named after the
   policy that GENERATED it and not after the iteration that consumed it.
2. **Extract prompts.** Slice each conversation after every patient turn whose
   conversation-so-far has at least ``MIN_CONV_LENGTH`` utterances. Each slice carries the
   chat-templated ``prompt`` TRL samples from and the plain-text ``transcript`` the oracle
   grades, plus the ids look-ahead needs to continue against the right patient.
3. **Train.** ``GRPOTrainer`` samples ``G`` completions per prompt, the reward function scores
   each one (through the K-turn look-ahead when ``K > 0``), advantages are group-relative
   ``(r - mean)/std`` over the G siblings, and the loss is a PPO-style clip plus a KL penalty
   against the iteration's reference -- the adapter as it stood when the iteration started.
4. **Save.** Per-epoch checkpoints under ``iteration_N/training/``, the final adapter at
   ``iteration_N/adapter/``, whose EXISTENCE is the definition of "this iteration is done".

Five things in here are load-bearing and look like details
----------------------------------------------------------
**LoRA is attached BEFORE the trainer, never handed to it as ``peft_config``.** The reward
closure captures the policy object so that look-ahead rolls out under the weights being trained.
If the trainer were the one to wrap the model, the closure would hold the *unwrapped base* and
every look-ahead turn of the first iteration would be generated by a policy with no adapter --
silently, since a freshly-initialised LoRA is numerically identity at step 0 and only diverges as
training proceeds. :func:`ensure_peft_policy` closes that gap, and it runs AFTER generation so
that ``model_iter_0`` really is the untrained base.

**``per_device_train_batch_size`` counts COMPLETIONS, not prompts**, and
``gradient_accumulation_steps`` must never be collapsed to 1. Both are spelled out at the config
site in :func:`build_grpo_config`, which is where somebody would otherwise "optimise" them.

**The EDA recorder is reloaded from the checkpoint on resume.** HuggingFace resumes by
fast-forwarding through batches that were already consumed, and a fast-forwarded batch never
re-invokes the reward function. Without the snapshot reload an interrupted iteration's
``generations.jsonl`` silently contains only the rows produced after the resume point.

**Timing is written through ``core.timing.log_session``, and that is the ONLY timing record.**
Exp3's per-process fields undercounted a resumed iteration by up to 2x and cost 1,336 LOC of
artifact-mtime archaeology to repair. Every phase this module measures gets logged; nothing is
reconstructed later.

**``run_metadata.json`` is rewritten each process, but the superseded payload survives** in
``run_metadata_history.jsonl``. Exp3 overwrote in place, so a resume under changed knobs
restamped the whole arm -- earlier iterations included -- and the values those iterations really
ran under were simply gone.

Import order
------------
``trl`` is imported before torch. On the local Blackwell card (sm_120) the other order segfaults
at CUDA init with no traceback, so this module calls
:func:`core.runtime.assert_import_order` at import time to turn a silent exit 139 into a message.

Two name collisions, on purpose
-------------------------------
:func:`build_grpo_config` and :func:`write_run_metadata` share their names with functions in
``core.config`` that do different jobs (``core.config`` builds the frozen CONFIG BUNDLE from
cell-1 globals and serialises a prepared payload; these build a ``trl.GRPOConfig`` and compose
that payload). The names are fixed by the module contract. **Do not star-import both modules into
one notebook namespace** -- import this module qualified (``from grpo import grpo_trainer``) or
use the unambiguous aliases :func:`build_trl_grpo_config` / :func:`write_arm_metadata`.
"""

