def _warn(message: str) -> None:
    """One-line warning channel. Printed, not ``warnings.warn``: a notebook shows print output
    inline and swallows warnings into a filter nobody set."""
    print(f"{_LOG}WARNING: {message}")


def _write_json_atomic(path: str, payload: Mapping[str, Any]) -> str:
    """Write JSON via a temp file plus ``os.replace``.

    A crash mid-write must never leave an unparseable ``iteration_metadata.json`` behind: the
    file sits next to an adapter that reads as a completed iteration, and a reader that fails on
    it cannot tell "torn write" from "this arm was never configured".
    """
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(to_jsonable(dict(payload)), fh, indent=2, allow_nan=False)
    os.replace(tmp, path)
    return path


