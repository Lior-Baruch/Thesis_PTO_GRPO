def save_iteration_checkpoint(
    *,
    policy,
    tokenizer,
    paths: RunPaths,
    iteration: int,
    metadata: Mapping[str, Any],
) -> str:
    """Write ``iteration_metadata.json``, then the adapter. Returns the adapter directory.

    Args:
        policy: the trained policy (``trainer.model``).
        tokenizer: saved beside the adapter so the checkpoint carries its own ChatML template.
        paths: the run's :class:`~core.config.RunPaths`.
        iteration: which iteration is being closed out.
        metadata: the iteration record -- counts, timings, arm identity.

    Returns:
        ``iteration_N/adapter``.

    Notes:
        **Order matters: metadata first, adapter last.** The adapter directory's existence is the
        ONLY definition of "this iteration is done" (``core.policy.list_iteration_checkpoints``,
        the resume logic, the EDA and the eval-generation tool all key on it). Writing the
        adapter first and dying before the metadata would leave an iteration that reads as
        complete with no record of what it cost or how it was configured; writing the metadata
        first and dying leaves an incomplete iteration with a stale sidecar, which the next
        resume simply overwrites.

        The epoch checkpoint list is captured from ``iteration_N/training`` before either write,
        so the record names the checkpoints ``save_total_limit`` actually left on disk.
    """
    iter_dir = paths.ensure_iteration_dir(iteration)
    training_dir = paths.training_dir(iteration)
    adapter_dir = paths.adapter_dir(iteration)

    checkpoints = [os.path.basename(c) for c in list_hf_checkpoints(training_dir)]
    payload = {**dict(metadata), "epoch_checkpoints": checkpoints}
    _write_json_atomic(paths.iteration_metadata_path(iteration), payload)

    os.makedirs(adapter_dir, exist_ok=True)
    policy.save_pretrained(adapter_dir)
    tokenizer.save_pretrained(adapter_dir)

    print(f"{_LOG}Saved adapter -> {adapter_dir}")
    print(f"{_LOG}Epoch checkpoints kept: {checkpoints or '(none)'}")
    print(f"{_LOG}Iteration metadata -> {os.path.join(iter_dir, 'iteration_metadata.json')}")
    return adapter_dir


def push_adapter_to_hub(
    policy,
    cfg: GRPOTrainingConfig,
    *,
    iteration: Optional[int] = None,
    commit_message: Optional[str] = None,
) -> bool:
    """Push the current adapter to the Hub, if this arm is configured to.

    Args:
        policy: the PEFT-wrapped policy.
        cfg: ``push_to_hub`` and ``hub_entity`` decide whether anything happens;
            ``cfg.adapter_repo`` is ``<hub_entity>/<EXPERIMENT_NAME>``.
        iteration: stamped into the default commit message.
        commit_message: overrides the default.

    Returns:
        True when a push succeeded, False when it was skipped or failed.

    Notes:
        **A failed push never aborts training.** It is a safety net on top of the local adapter,
        not the artifact itself: the local copy on Drive is what the next iteration resumes from
        and what the EDA reads. Losing a Colab session to a Hub 500 would be the expensive
        failure.
    """
    if not cfg.push_to_hub:
        return False
    repo = cfg.adapter_repo
    if not repo:
        _warn("push_to_hub is set but hub_entity is empty; there is nowhere to push")
        return False
    message = commit_message or (
        f"iteration_{iteration}/{cfg.num_iterations}" if iteration is not None else "adapter"
    )
    try:
        policy.push_to_hub(repo_id=repo, commit_message=message)
    except Exception as exc:  # noqa: BLE001 - the local adapter is the artifact
        _warn(f"Hub push to {repo} failed ({type(exc).__name__}: {exc}); the local adapter is intact")
        return False
    print(f"{_LOG}Pushed adapter -> {repo} ({message})")
    return True


def write_run_metadata(
    cfg: GRPOTrainingConfig,
    roles: RolesConfig,
    gen: GenConfig,
    oracle_cfg: Any,
    la_cfg: Any,
    paths: RunPaths,
    *,
    extra: Optional[Mapping[str, Any]] = None,
) -> str:
    """Write ``run_metadata.json`` and append this process's payload to the history log.

    Args:
        cfg, roles, gen, oracle_cfg, la_cfg, paths: the whole config bundle, in any order --
        ``core.config.config_to_metadata`` indexes them by type. Passing the COMPLETE bundle
        matters: the completeness assertion that guarantees every silently-mutable knob reached
        the payload only runs when all six sections are present.
        extra: anything runtime-only worth recording under a ``runtime`` key -- the host banner,
            the realized look-ahead sub-batch, the oracle-sanity report.

    Returns:
        The path of ``run_metadata.json``.

    Notes:
        This is a composition of ``core.config.config_to_metadata`` and
        ``core.config.write_run_metadata``, not a second implementation.

        **The history log is the point (Exp3 fix #5).** The current file is overwritten -- a
        reader wants exactly one "what is this arm configured as?" -- but every process appends
        its own line to ``run_metadata_history.jsonl`` first, so a resume under changed knobs
        leaves a trace instead of restamping the whole arm, earlier iterations included.

        Call it once per process, at the start. ``EXPERIMENT_NAME`` encodes only the arm's
        identity axes, so a changed learning rate, tau, temperature or sub-batch produces a
        byte-identical folder name and this file is the ONLY thing that can tell the two runs
        apart.
    """
    payload = config_to_metadata(cfg, roles, gen, oracle_cfg, la_cfg, paths)
    if extra:
        payload["runtime"] = to_jsonable(dict(extra))
    path = _write_metadata_payload(payload, paths)
    print(f"{_LOG}Run metadata -> {path}")
    return path


