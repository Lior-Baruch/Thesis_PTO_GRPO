def run_generation_phase(
    *,
    policy,
    tokenizer,
    client,
    roles: RolesConfig,
    gen: GenConfig,
    primitives: AsyncPrimitives,
    permutations: Sequence[Dict[str, str]],
    therapist_system_prompt: str,
    therapist_init_utterance: str,
    conv_dir: str,
    persona_ids: Sequence[int],
    patient_seed: Optional[int] = None,
    label: str = "",
) -> Tuple[List[Any], float]:
    """Simulate this iteration's conversations and write them to *conv_dir*.

    Args:
        policy: the CURRENT therapist policy. Switched to ``eval()`` with ``use_cache=True`` here
            and left that way -- :func:`run_training_phase` switches it back, so a caller that
            generates without training must do so itself.
        client: async client for the patient role.
        roles: supplies ``roles.patient`` (model, per-attempt timeout, retries, extra_body).
        gen: conversation-shaping knobs (length, temperatures, batch size, stop strings).
        primitives: the shared loop-keyed semaphores and GPU lock.
        permutations: the FULL ``generate_all_permutations()`` list in canonical order. It is
            indexed by persona id, so a shuffled subset here would silently pair each
            conversation with the wrong patient.
        conv_dir: ``conversations/<ARM>/model_iter_<N>``. Conversations already on disk there are
            reloaded, not regenerated, which is what makes a killed generation phase cheap to
            resume.
        persona_ids: which personas to run, in processing order (see :func:`select_persona_ids`).
        patient_seed: forwarded to the patient API when the backend honours it.
        label: printed in the phase banner.

    Returns:
        ``(states, seconds)`` -- the usable conversations, sorted by persona id, and the
        wall-clock this process spent here. The seconds go straight into
        ``core.timing.log_session``; they are per-process by construction, which is correct,
        because the session log sums across processes rather than trusting any one of them.

    Notes:
        ``batch_size`` is a SAFETY setting on the local 12 GB card, not a throughput knob:
        weights plus roughly 1.1 GB per concurrent conversation, and an over-budget VRAM request
        there reboots the machine instead of raising. On the A100 a large batch is what amortises
        the patient round-trip across the whole batch.
    """
    start = time.time()
    banner = f" ({label})" if label else ""
    print(f"\n{_LOG}-- Generation{banner}: {len(persona_ids)} conversations -> {conv_dir}")

    policy.eval()
    policy.config.use_cache = True

    states = generate_all_conversations(
        policy,
        tokenizer,
        client,
        roles.patient,
        primitives,
        permutations,
        therapist_system_prompt,
        therapist_init_utterance,
        persona_ids=list(persona_ids),
        save_dir=conv_dir,
        num_utterances=gen.num_utterances_for_data,
        max_tokens=gen.max_tokens_per_response,
        temperature_therapist=gen.temperature_therapist,
        temperature_patient=gen.temperature_patient,
        therapist_max_input_tokens=gen.therapist_max_input_tokens,
        # [] = no string stopping (Instruct arms); None would fall back to the ChatML defaults.
        stop_strings=list(gen.stop_strings),
        patient_seed=patient_seed,
        batch_size=gen.conversation_batch_size,
        max_retries_without_progress=gen.max_retries_without_progress,
        verbose=gen.verbose,
        verbose_detailed=gen.verbose_detailed,
    )

    seconds = time.time() - start
    avg_len = (sum(s.n_utterances for s in states) / len(states)) if states else 0.0
    print(
        f"{_LOG}Generated {len(states)}/{len(persona_ids)} conversations in {seconds:.1f}s "
        f"(avg {avg_len:.1f} utterances)"
    )
    return states, seconds


