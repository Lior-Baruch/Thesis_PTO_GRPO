def run_training_phase(
    *,
    policy,
    tokenizer,
    grpo_args: GRPOConfig,
    reward_funcs,
    train_dataset: Dataset,
    eval_dataset: Optional[Dataset],
    iteration: int,
    iter_metadata: Optional[Mapping[str, Any]] = None,
    recorder: Optional[EDARecorder] = None,
    resume_checkpoint: Optional[str] = None,
    tb_log_dir: Optional[str] = None,
) -> Tuple[Any, int, float]:
    """Build a ``GRPOTrainer``, train it, and hand the trainer back.

    Args:
        policy: the PEFT-wrapped policy from :func:`ensure_peft_policy`. It is the SAME object
            the reward closure captured, which is what makes look-ahead roll out under the
            weights being trained.
        grpo_args: from :func:`build_grpo_config`.
        reward_funcs: the async callable from ``core.reward.make_reward_fn``.
        eval_dataset: ``None`` disables evaluation; ``grpo_args.eval_strategy`` must already
            agree.
        iter_metadata: copied into every checkpoint by :class:`CheckpointMetadataCallback`.
        recorder: snapshotted into every checkpoint by the same callback.
        resume_checkpoint: an HF ``checkpoint-*`` path, or ``None``. Applies to THIS call only --
            the caller must not pass it again for the next iteration.
        tb_log_dir: defaults to ``<output_dir>/tb_logs``.

    Returns:
        ``(trainer, step_delta, seconds)``. ``step_delta`` counts only steps executed in THIS
        call: on a resume, ``trainer.state.global_step`` includes the fast-forwarded ones, and
        adding those to the cumulative offset again would double-count the TensorBoard x-axis.

    Notes:
        **``peft_config`` is always ``None``.** The adapter is attached before the trainer exists
        (see :func:`ensure_peft_policy`); handing TRL a config as well would wrap an already
        wrapped model, and the nested ``adapter_config.json`` no longer describes the model you
        think it does.

        **The TensorBoard directory is set BEFORE the trainer is constructed.**
        ``TensorBoardCallback.__init__`` reads its environment variable once and keeps the value,
        and HF's fallback ``default_logdir()`` builds a clock-and-hostname name that is not a
        legal Windows path segment -- Exp3 collected ``WinError 123`` from it. The
        post-construction patch re-points a callback that was built anyway (a resumed iteration
        can reuse one whose directory was captured from a previous environment).

        **``patch_generate`` runs on both sides of ``train()``.** The trainer hands back a fresh
        ``generate`` when it builds its wrapper, and ``train()`` may rebuild it again; an
        unpatched ``generate`` ignores ``stop_strings`` silently and the anti-degeneracy stack
        loses its first line of defence.

        The policy is put in ``train()`` with ``config.use_cache = False`` -- the training
        setting, and what gradient checkpointing requires. TRL's own sampling passes an explicit
        ``generation_config`` whose ``use_cache`` is True, so in-loop generation still uses the
        KV cache; the look-ahead rollout toggles ``eval()`` + ``use_cache`` itself and restores
        both in a ``finally``, because it runs mid-optimizer-step.

        Each iteration builds a FRESH trainer, so the Adam moments reset every iteration while
        the LoRA weights carry over -- a warm restart per iteration. That is deliberate and is
        matched on the PTO side; it is not an artefact of the loop structure.
    """
    start = time.time()
    log_dir = tb_log_dir or os.path.join(grpo_args.output_dir, TB_SUBDIR)
    report_to = [str(t) for t in (getattr(grpo_args, "report_to", None) or [])]

    policy.config.use_cache = False
    policy.train()

    # Must precede the Trainer: the callback reads the env var in __init__ and keeps it.
    setup_tensorboard_logging(log_dir)

    trainer = GRPOTrainer(
        model=policy,
        args=grpo_args,
        processing_class=tokenizer,
        reward_funcs=reward_funcs,
        train_dataset=train_dataset,
        eval_dataset=eval_dataset,
        peft_config=None,  # the adapter is already attached -- see ensure_peft_policy
        callbacks=[
            CheckpointMetadataCallback(
                iteration=iteration, metadata=iter_metadata or {}, recorder=recorder
            )
        ],
    )

    if "tensorboard" in report_to:
        patch_trainer_tensorboard_callback(trainer, log_dir)

    patch_generate(trainer.model, tokenizer)

    resumed_steps = 0
    if resume_checkpoint:
        try:
            resumed_steps = int(os.path.basename(resume_checkpoint).split("-")[-1])
        except ValueError:
            resumed_steps = 0
        print(f"{_LOG}Resuming from {os.path.basename(resume_checkpoint)} ({resumed_steps} steps)")

    trainer.train(resume_from_checkpoint=resume_checkpoint or None)

    patch_generate(trainer.model, tokenizer)

    step_delta = max(0, int(trainer.state.global_step) - resumed_steps)
    seconds = time.time() - start
    print(f"{_LOG}Training complete in {seconds:.1f}s ({step_delta} new optimizer steps)")
    return trainer, step_delta, seconds


