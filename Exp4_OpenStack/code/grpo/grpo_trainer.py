class CheckpointMetadataCallback(TrainerCallback):
    """On every checkpoint save: write provenance, and snapshot the EDA buffer beside it.

    Args:
        iteration: the iteration being trained, stamped into the provenance file.
        metadata: the iteration's base metadata dict (arm name, rubric, K, MCL, ...). Copied
            into every checkpoint so a checkpoint dug out of Drive months later is
            self-describing.
        recorder: the iteration's :class:`~core.recorder.EDARecorder`, or ``None``.

    Notes:
        **The snapshot is the reason this callback exists.** HuggingFace resumes an interrupted
        run by fast-forwarding through the batches it already consumed, and a fast-forwarded
        batch never re-invokes the reward function -- so the branch records those steps produced
        are gone unless they were written down. Snapshotting INTO the checkpoint dir binds the
        snapshot to the exact checkpoint
        :func:`core.policy.get_latest_valid_hf_checkpoint` will walk back to, so the reload in
        :func:`run_one_iteration` can never restore rows from a checkpoint that was not the one
        resumed from.

        Both files are extra payload inside ``checkpoint-N/`` and are absent from
        ``core.policy.HF_TRAINER_FILES``, so writing them cannot make a checkpoint look valid,
        and failing to write them cannot make one look corrupt.

        Every failure here is swallowed after a warning. Telemetry must never be able to abort an
        optimizer step that cost GPU-hours to reach.
    """

    def __init__(self, *, iteration: int, metadata: Mapping[str, Any], recorder=None) -> None:
        self.iteration = int(iteration)
        self.metadata = dict(metadata or {})
        self.recorder = recorder

    def on_save(self, args, state, control, **kwargs):  # noqa: D102 - TrainerCallback protocol
        checkpoint_dir = os.path.join(args.output_dir, f"checkpoint-{state.global_step}")
        if not os.path.isdir(checkpoint_dir):
            # HF names the directory from global_step; if it is not there yet this hook fired for
            # a save that did not land, and writing our sidecars would create a phantom dir.
            return control
        try:
            _write_json_atomic(
                os.path.join(checkpoint_dir, EXPERIMENT_METADATA_FILENAME),
                {
                    **self.metadata,
                    "iteration": self.iteration,
                    "global_step": int(state.global_step),
                    "epoch": (None if state.epoch is None else float(state.epoch)),
                    "written_at": time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime()),
                },
            )
        except Exception as exc:  # noqa: BLE001 - provenance must not fail a run
            _warn(f"could not write {EXPERIMENT_METADATA_FILENAME} ({exc})")

        if self.recorder is not None and getattr(self.recorder, "enabled", False):
            try:
                self.recorder.snapshot_to(os.path.join(checkpoint_dir, EDA_SNAPSHOT_FILENAME))
            except Exception as exc:  # noqa: BLE001
                _warn(f"could not snapshot the EDA buffer ({exc})")
        return control


