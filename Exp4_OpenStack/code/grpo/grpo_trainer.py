def _grpo_config_fields() -> frozenset:
    return frozenset(f.name for f in dataclasses.fields(GRPOConfig))


def build_grpo_config(
    cfg: GRPOTrainingConfig,
    gen: GenConfig,
    *,
    output_dir: str,
    num_train_prompts: int,
    has_eval: bool = True,
    tb_log_dir: Optional[str] = None,
    tokenizer=None,
) -> GRPOConfig:
    """Assemble the ``trl.GRPOConfig`` for one iteration.

    Args:
        cfg: the frozen training config (batch arithmetic, GRPO knobs, checkpointing).
        gen: supplies the stop strings TRL must sample against.
        output_dir: ``iteration_N/training`` -- the HF Trainer output dir, where
            ``checkpoint-*`` and ``tb_logs/`` land.
        num_train_prompts: length of the train dataset, used only to size the LR warmup.
        has_eval: False disables evaluation entirely (an empty held-out split).
        tb_log_dir: TensorBoard directory; defaults to ``<output_dir>/tb_logs``.
        tokenizer: the therapist tokenizer. Required when ``gen.stop_strings`` is empty (an
            Instruct-therapist arm): TRL's in-loop sampling then stops on the
            ``therapist_stop_token_ids`` eos list passed through ``generation_kwargs``
            instead of on stop strings.

    Returns:
        A ``GRPOConfig``.

    Raises:
        RuntimeError: the pinned TRL does not accept one of :data:`_CRITICAL_GRPO_FIELDS`. A
            renamed cosmetic field is dropped with a warning; a renamed critical one would
            change what is trained while looking like it worked, so it stops the run.

    Notes:
        **``per_device_train_batch_size`` counts COMPLETIONS, not prompts.** TRL's
        ``RepeatSampler`` emits ``num_generations`` completions per prompt, so the unique prompts
        consumed per optimizer step are
        ``(per_device / num_generations) * gradient_accumulation_steps = (64/8) * 2 = 16`` --
        matched to PTO's 16 preference pairs per step so the two methods take
        comparable-sized steps. Read that number off ``cfg.prompts_per_step``.

        **Keep ``gradient_accumulation_steps=2`` for the prompts/step match, not for gradient
        scale.** On the pinned trl 1.4.0, ``gas`` changes are gradient-scale-NEUTRAL: trl
        bypasses transformers' own ``training_step`` scaling by passing a non-None
        ``compute_loss_func`` sentinel (installed trl ``grpo_trainer.py`` ~:652-657) and divides
        the loss exactly once by ``current_gradient_accumulation_steps`` (~:2351-2352). The old
        "net scale is 1/gas^2, halving gas doubles the gradient" story was measured on Exp3's
        earlier stack and is FALSE here -- re-verify those two line references on any trl bump.
        What ``gas=2`` still buys is the design match: 128 completions -> 16 unique prompts per
        optimizer step, mirrored to PTO's 16 pairs.

        **And a bigger batch buys nothing.** TRL already issues ONE ``generate()`` per optimizer
        step over the whole ``generation_batch_size`` (``per_device x gas``), so ``64 x 2`` and
        ``128 x 1`` emit the same single call. There is no throughput on the table here.

        **``generation_kwargs`` carries the stop mechanism and is not optional.** On a
        BASE-therapist arm it is ``{"stop_strings": ...}``: ``<|im_end|>`` is template text,
        not the base tokenizer's EOS, so without it the 1B policy samples straight through the
        marker to ``max_completion_length`` and writes the patient's reply itself -- polluting
        the transcript the oracle grades AND, because GRPO credits every sampled token, training
        the policy toward 200-token rambles. ``core.policy.patch_generate`` is what makes
        ``stop_strings`` take effect at all -- HuggingFace ignores it silently unless a
        tokenizer is passed to the same call, and TRL does not pass one. On an
        INSTRUCT-therapist arm (empty ``gen.stop_strings``) it is
        ``{"eos_token_id": therapist_stop_token_ids(tokenizer)}`` instead: the Llama-3 turn
        markers are single special tokens there, so token-id stopping is exact and skips the
        per-call stop-string criteria build.

        **``remove_unused_columns=False`` is required.** Without it TRL strips ``transcript``,
        ``persona_id`` and ``patient_system_prompt`` and the reward function cannot grade or look
        ahead; see :data:`DATASET_COLUMNS`.

        The warmup is computed from the real prompts-per-step. Getting it wrong only mis-sizes
        the warmup itself -- the HF Trainer recomputes the cosine horizon from the actual
        dataloader length -- but Exp3 printed a figure ``num_generations`` too small, which read
        like a broken schedule for a year.
    """
    prompts_per_step = max(1, int(cfg.prompts_per_step))
    steps_per_epoch = max(1, math.ceil(max(1, int(num_train_prompts)) / prompts_per_step))
    total_steps = max(1, steps_per_epoch * int(cfg.epochs_per_iteration))
    warmup_steps = max(0, math.ceil(total_steps * float(cfg.warmup_steps_ratio)))

    if num_train_prompts < prompts_per_step:
        _warn(
            f"only {num_train_prompts} train prompts for {prompts_per_step} prompts/step -- this "
            f"iteration takes a single, padded optimizer step per epoch."
        )

    log_dir = tb_log_dir or os.path.join(output_dir, TB_SUBDIR)
    os.makedirs(log_dir, exist_ok=True)

    print(
        f"{_LOG}GRPO batch: per_device {cfg.train_batch_size} completions x gas "
        f"{cfg.gradient_accumulation_steps} = {cfg.generation_batch_size} completions -> "
        f"{prompts_per_step} prompts/step (G={cfg.num_generations})"
    )
    print(
        f"{_LOG}Schedule: {steps_per_epoch} steps/epoch x {cfg.epochs_per_iteration} epochs = "
        f"{total_steps} steps, warmup {warmup_steps} (ratio {cfg.warmup_steps_ratio})"
    )

    kwargs: Dict[str, Any] = {
        "output_dir": output_dir,
        "run_name": cfg.adapter_repo or cfg.experiment_name,
        "hub_model_id": cfg.adapter_repo or None,
        "push_to_hub": False,  # pushing is done explicitly, per iteration, in push_adapter_to_hub
        # -- batch arithmetic (see the Notes: completions, not prompts; never collapse gas) --
        "per_device_train_batch_size": cfg.train_batch_size,
        "per_device_eval_batch_size": cfg.eval_batch_size,
        "gradient_accumulation_steps": cfg.gradient_accumulation_steps,
        "num_train_epochs": cfg.epochs_per_iteration,
        # -- GRPO proper --
        "num_generations": cfg.num_generations,
        "num_iterations": cfg.grpo_inner_iterations,  # inner PPO iterations (mu), NOT the arm loop
        "beta": cfg.grpo_beta,                        # KL against the iteration-start reference
        "temperature": cfg.grpo_temperature,
        "loss_type": cfg.grpo_loss_type,
        "scale_rewards": "group",                     # A = (r - mean_g) / std_g over the G siblings
        "max_completion_length": cfg.max_completion_length,
        # Without this the base policy self-plays the patient to the token cap (see the Notes).
        # Base-therapist arms stop on the ChatML strings; Instruct arms have EMPTY stop_strings
        # and stop on the eos-id list instead -- <|eot_id|>/<|eom_id|>/<|start_header_id|> are
        # single special tokens there, so token-id stopping is exact and costs nothing per call.
        "generation_kwargs": (
            {"stop_strings": list(gen.stop_strings)} if gen.stop_strings
            else ({"eos_token_id": therapist_stop_token_ids(tokenizer)}
                  if tokenizer is not None else None)
        ),
        # Required: TRL would otherwise strip every column the reward fn reads.
        "remove_unused_columns": False,
        # -- optimizer --
        "learning_rate": cfg.learning_rate,
        "lr_scheduler_type": "cosine",
        "warmup_steps": warmup_steps,
        "gradient_checkpointing": cfg.gradient_checkpointing,
        "bf16": True,
        "seed": cfg.seed,
        # -- checkpointing / logging --
        "logging_steps": cfg.logging_steps,
        "save_strategy": cfg.save_strategy,
        "save_steps": cfg.save_steps,
        "save_total_limit": cfg.save_total_limit,
        "report_to": list(cfg.report_to),
        "log_completions": cfg.log_completions,
        "eval_strategy": "epoch" if has_eval else "no",
    }
    if cfg.gradient_checkpointing:
        # Re-entrant checkpointing does not compose with PEFT's frozen base parameters.
        kwargs["gradient_checkpointing_kwargs"] = {"use_reentrant": False}

    known = _grpo_config_fields()
    unknown = sorted(k for k in kwargs if k not in known)
    critical_missing = [k for k in unknown if k in _CRITICAL_GRPO_FIELDS]
    if critical_missing:
        raise RuntimeError(
            f"the installed trl does not accept {critical_missing} on GRPOConfig. These decide "
            f"WHAT is trained (group size, KL, reward scaling, the column passthrough), so they "
            f"cannot be dropped silently -- a run without them would look successful and train "
            f"something else. Pin trl to the version in requirements.txt, or port this config "
            f"site to the new field names."
        )
    for name in unknown:
        _warn(f"GRPOConfig has no field {name!r} in the installed trl; dropping it")
        kwargs.pop(name, None)

    return GRPOConfig(**kwargs)


#: Unambiguous alias. ``core.config.build_grpo_config`` builds the frozen CONFIG BUNDLE from
#: cell-1 globals; this one builds TRL's trainer arguments. Use this name when both modules are
#: imported into one namespace.
build_trl_grpo_config = build_grpo_config


